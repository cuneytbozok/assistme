/**
 * Native-messaging host installer (ARCHITECTURE §4.1, §11).
 *
 * Writes a wrapper script (absolute Node + host script, 0755) and a Chrome host manifest
 * (0644) whose `allowed_origins` has exactly this extension's origin. Refuses any path whose
 * directories another user could write to, since that user could swap the code Chrome runs.
 */
import { execFileSync } from 'node:child_process';
import {
  chmodSync,
  existsSync,
  lstatSync,
  mkdirSync,
  readFileSync,
  realpathSync,
  renameSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { homedir } from 'node:os';
import { basename, dirname, isAbsolute, join, parse } from 'node:path';
import { EXTENSION_ORIGIN, NATIVE_HOST_NAME } from '@sn-mcp/shared';

export interface InstallPaths {
  nodePath: string;
  hostScript: string;
  installDir: string;
  manifestDir: string;
}

export interface InstallPlan {
  wrapperPath: string;
  wrapperContent: string;
  manifestPath: string;
  manifest: {
    name: string;
    description: string;
    path: string;
    type: 'stdio';
    allowed_origins: string[];
  };
}

export class InstallError extends Error {}

export function defaultInstallPaths(hostScript: string, nodePath = process.execPath): InstallPaths {
  const appSupport = join(homedir(), 'Library', 'Application Support');
  return {
    nodePath,
    hostScript,
    installDir: join(appSupport, 'sn-mcp', 'host'),
    manifestDir: join(appSupport, 'Google', 'Chrome', 'NativeMessagingHosts'),
  };
}

/**
 * macOS groups whose members can already become root (`admin` 80, `wheel` 0). A directory
 * writable by one of them (e.g. Homebrew's `/opt/homebrew/Cellar`, mode 775 group admin) adds
 * no exposure beyond what those users already have, so it is accepted. World-writable
 * directories and any other writable group are refused.
 */
export const ROOT_EQUIVALENT_GIDS = new Set([0, 80]);

/**
 * Every existing ancestor directory must be owned by `uid` or root, never world-writable, and
 * group-writable only by a root-equivalent group.
 */
export function assertSafeAncestors(path: string, uid: number): void {
  let dir = dirname(path);
  const root = parse(dir).root;
  for (;;) {
    if (existsSync(dir)) {
      const st = lstatSync(dir);
      if (st.isSymbolicLink()) throw new InstallError(`${dir} is a symlink`);
      if (st.uid !== uid && st.uid !== 0) {
        throw new InstallError(`${dir} is owned by another user (uid ${st.uid})`);
      }
      const worldWritable = (st.mode & 0o002) !== 0;
      const groupWritable = (st.mode & 0o020) !== 0 && !ROOT_EQUIVALENT_GIDS.has(st.gid);
      if (worldWritable || groupWritable) {
        throw new InstallError(
          `${dir} is writable by group or others (mode ${(st.mode & 0o777).toString(8)})`,
        );
      }
    }
    if (dir === root) return;
    dir = dirname(dir);
  }
}

function shellQuote(s: string): string {
  return `'${s.replace(/'/g, `'\\''`)}'`;
}

export function planInstall(
  paths: InstallPaths,
  uid: number,
  options: { capture?: boolean } = {},
): InstallPlan {
  for (const [label, p] of Object.entries(paths)) {
    if (!isAbsolute(p)) throw new InstallError(`${label} must be an absolute path: ${p}`);
  }
  if (!existsSync(paths.nodePath)) throw new InstallError(`Node not found at ${paths.nodePath}`);
  if (!existsSync(paths.hostScript)) {
    throw new InstallError(
      `Host script not found at ${paths.hostScript} — run npm run build first`,
    );
  }
  const nodePath = realpathSync(paths.nodePath);
  const hostScript = realpathSync(paths.hostScript);
  assertSafeAncestors(nodePath, uid);
  assertSafeAncestors(hostScript, uid);
  const wrapperPath = join(paths.installDir, 'native-host');
  const manifestPath = join(paths.manifestDir, `${NATIVE_HOST_NAME}.json`);
  assertSafeAncestors(wrapperPath, uid);
  assertSafeAncestors(manifestPath, uid);
  return {
    wrapperPath,
    wrapperContent: `#!/bin/sh\n# sn-mcp native messaging host (generated by install-native-host)\n${options.capture ? "# DEV ONLY: broker traffic capture (T-009). Reinstall without --capture to disable.\nexport SN_MCP_CAPTURE='metadata+bodies-redacted'\n" : ''}exec ${shellQuote(nodePath)} ${shellQuote(hostScript)} "$@"\n`,
    manifestPath,
    manifest: {
      name: NATIVE_HOST_NAME,
      description: 'sn-mcp broker: read-only ServiceNow MCP connector',
      path: wrapperPath,
      type: 'stdio',
      allowed_origins: [EXTENSION_ORIGIN],
    },
  };
}

function writeAtomic(path: string, content: string, mode: number): void {
  const tmp = `${path}.tmp-${process.pid}`;
  writeFileSync(tmp, content, { mode, flag: 'w' });
  chmodSync(tmp, mode);
  renameSync(tmp, path);
}

export function applyInstall(plan: InstallPlan): void {
  mkdirSync(dirname(plan.wrapperPath), { recursive: true, mode: 0o700 });
  mkdirSync(dirname(plan.manifestPath), { recursive: true, mode: 0o755 });
  writeAtomic(plan.wrapperPath, plan.wrapperContent, 0o755);
  writeAtomic(plan.manifestPath, `${JSON.stringify(plan.manifest, null, 2)}\n`, 0o644);
}

export function uninstall(paths: Pick<InstallPaths, 'installDir' | 'manifestDir'>): string[] {
  const removed: string[] = [];
  for (const p of [
    join(paths.manifestDir, `${NATIVE_HOST_NAME}.json`),
    join(paths.installDir, 'native-host'),
  ]) {
    if (existsSync(p)) {
      rmSync(p);
      removed.push(p);
    }
  }
  return removed;
}

/** Node versions the project supports (FR-9). */
export function nodeIsSupported(version: string, minimumMajor = 22): boolean {
  const major = Number.parseInt(version.replace(/^v/, ''), 10);
  return Number.isInteger(major) && major >= minimumMajor;
}

/** True only if `pid` is running and its command line is the sn-mcp native host. */
function isOurHost(pid: number): boolean {
  try {
    process.kill(pid, 0);
    const cmd = execFileSync('ps', ['-o', 'command=', '-p', String(pid)], { encoding: 'utf8' });
    // Exactly our script: other programs have similar names (chrome-native-host).
    return /\/native-host\.js(\s|$)/.test(cmd);
  } catch {
    return false;
  }
}

async function stopHost(lockFile: string): Promise<boolean> {
  if (!existsSync(lockFile)) return false;
  const pid = Number.parseInt(readFileSync(lockFile, 'utf8').trim(), 10);
  // A stale lock may name an unrelated process by now: never signal anything else.
  if (!Number.isInteger(pid) || pid <= 1 || !isOurHost(pid)) return false;
  process.kill(pid, 'SIGTERM');
  for (let i = 0; i < 40 && isOurHost(pid); i++) {
    await new Promise((resolve) => setTimeout(resolve, 50));
  }
  return true;
}

/**
 * Full removal (T-037): stops the running native host, then removes its Chrome manifest and the
 * sn-mcp folder (wrapper, socket, key, lock, logs, any capture file). A symlink at the folder's
 * path is removed as a link and never followed.
 */
export async function uninstallAll(
  paths: Pick<InstallPaths, 'installDir' | 'manifestDir'>,
  runtimeDir: string,
): Promise<{ removed: string[]; stoppedHost: boolean }> {
  if (basename(runtimeDir) !== 'sn-mcp') {
    throw new InstallError(`Refusing to remove ${runtimeDir}: not an sn-mcp folder`);
  }
  // First the manifest, so Chrome can't start a new host while the old one stops.
  const removed = uninstall(paths);
  const stoppedHost = await stopHost(join(runtimeDir, 'broker.pid'));
  if (existsSync(runtimeDir)) {
    rmSync(runtimeDir, { recursive: true, force: true });
    removed.push(runtimeDir);
  }
  return { removed, stoppedHost };
}
